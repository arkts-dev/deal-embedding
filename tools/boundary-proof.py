#!/usr/bin/env python3
"""Standalone build boundary, proven instead of asserted.

1. The declared library input set (tools/library-inputs.txt) is audited: nothing under
   demos/ or tests/ and nothing outside the library and its pinned dependencies.
2. The library is rebuilt in a staged tree where `demos` and `tests` are access-failing
   sentinels, and the produced class and asset content digests must equal the canonical
   packaged AAR. A build that read application source cannot succeed there.
3. Every demo target's real compile declaration is audited - application sources plus the packaged
   AAR extraction, the pinned runtime and the platform SDK only - and every demo target is then
   compiled and packaged by the production target loop against that extraction.
4. Both negative controls are executed through the gate the compile consumes: a demo/test path added
   to library inputs, and a framework implementation source or a library build tree jar injected into a
   demo target's declaration. Each must be reported with the offending path.

The isolated proof is cached only for identical validated inputs; a changed input invalidates it, and
an unchanged demo target keeps its compile proof. The isolated build and the demo repackage share no
output tree, so one cold proof prepares both at the same time, each under its own declared bound.
Nothing tracked is modified.
"""
