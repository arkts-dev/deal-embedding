EXTRACTION = ROOT / 'build/embedding-consumer'
CACHE = ROOT / 'build/verification/standalone-boundary.json'
COMPILE_CACHE = ROOT / 'build/verification/demo-compile'
STAGE = ROOT / 'build/verification/boundary'
STAGE_BOUNDS = ROOT / 'tools/stage-bounds.txt'


# One sentence for both owners of the derived bounds, so an operator reads the same rule from the proof and
# from the short-check lanes.
STAGE_OVERRIDE_REFUSAL = ('DEAL_BUILD_STAGE_SECONDS is not part of the derived bound; '
                          'change tools/stage-bounds.txt instead')


def stage_bounds():
    """The one per-stage preparation declaration `build.sh` also reads, so an outer bound can never be
    tighter than the inner bounds it contains."""
    table = {}
    for line in STAGE_BOUNDS.read_text().splitlines():
        parts = line.split()
        if not parts or parts[0].startswith('#'):
            continue
        if len(parts) < 2 or not parts[1].isdigit():
            raise SystemExit(f'standalone boundary: invalid preparation bound line: {line}')
        table[parts[0]] = int(parts[1])
    if not table:
        raise SystemExit('standalone boundary: no declared preparation bounds')
    return table


def isolated_build_seconds():
    """A whole proof compiles every stage in a tree that holds no canonical output; the sum of the
    declared bounds plus the conformance run is what a runaway cold proof may take before the stages
    themselves have each stopped with their own name."""
    return sum(stage_bounds().values()) + 30


# Every pending demo target is compiled, dexed, packaged and signed inside one batch. Measured cold on
# this toolchain: the seven declared targets over the two declared jobs take 327 s; a target's own
# validated-input stamp is what skips an unchanged repackage.
DEMO_PACKAGING_SECONDS = 900
# The batch overlaps targets until the host's core count, so a serial batch - one declared job, or a host
# that offers one core - sums every target instead of sharing the work. The bound therefore scales with
# the pending targets above the declared floor rather than failing the first cold proof on such a host.
DEMO_TARGET_SECONDS = 180
# Generated by the pinned Deal UI generator in JVM-run order; behaviour is proven by
# tests/tools/test-assistance.js, so a byte digest cannot be a stable boundary claim.
NONDETERMINISTIC_ASSETS = {'assistance/checkpoint-schema.js', 'assistance/experience_entry.js',
                           'assistance/experience_entry.deal.map.json'}
LIBRARY_SOURCE_TREES = ('android/src', 'core', 'ui', 'tools')


def demo_targets():
    """Every demo application directory, derived from the tree so a new demo cannot be skipped."""
    manifests = sorted((ROOT / 'demos/android/apps').glob('*/AndroidManifest.xml'))
    targets = [manifest.parent.name for manifest in manifests]
    if not targets:
        raise SystemExit('standalone boundary: no demo application is declared')
    return targets


def demo_packaging_seconds(pending):
    """The batch bound for the targets this proof must package: the declared floor, or one target's own
    preparation bound each when they run serially."""
    return max(DEMO_PACKAGING_SECONDS, DEMO_TARGET_SECONDS * len(pending))


# One cold proof: the isolated build, the batch for every declared target, then the audits.
PROOF_SECONDS = isolated_build_seconds() + demo_packaging_seconds(demo_targets()) + 60


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


library_inputs = load('library_inputs', ROOT / 'tools/library-inputs.py')
build_cache = load('build_cache', ROOT / 'tools/build-cache.py')


def sha(data):
    return hashlib.sha256(data).hexdigest()


def digest_map(entries):
    digest = hashlib.sha256()
    for name in sorted(entries):
        digest.update(name.encode() + b'\0' + entries[name].encode() + b'\n')
    return digest.hexdigest()


def normalize(data, replacements):
    """The compiler embeds absolute build paths in comments and location strings; compare the
    produced program, not the directory it happened to be built in."""
    for needle, token in replacements:
        data = data.replace(str(needle).encode(), token)
    return data


def aar_digests(aar, replacements=()):
    classes, assets = {}, {}
    with zipfile.ZipFile(aar) as archive:
        for name in archive.namelist():
            if name.endswith('/'):
                continue
            data = normalize(archive.read(name), replacements)
            if name == 'classes.jar':
                with zipfile.ZipFile(io.BytesIO(data)) as jar:
                    classes = {entry: sha(normalize(jar.read(entry), replacements))
                               for entry in jar.namelist() if not entry.endswith('/')}
            elif name.startswith('assets/'):
                assets[name[len('assets/'):]] = sha(data)
    return classes, assets


def compared(assets):
    return {name: value for name, value in assets.items() if name not in NONDETERMINISTIC_ASSETS}


def sdk_paths():
    sdk = Path(os.environ.get('ANDROID_SDK_ROOT') or Path.home() / 'Android/Sdk')
    android = sdk / 'platforms/android-37.0/android.jar'
    aidl = sdk / 'build-tools/36.0.0/aidl'
    aapt2 = sdk / 'build-tools/36.0.0/aapt2'
    for path in (android, aidl, aapt2):
        if not path.exists():
            raise SystemExit(f'standalone boundary: required toolchain input is absent: {path}')
    return android, aidl, aapt2


def compile_toolchain():
    """The compiler inputs the demo compile consumes; a target is only skipped when all of them are
    unchanged too, so a toolchain update cannot pass on a stale artifact."""
    kotlin = Path(os.environ.get('KOTLIN_HOME', '/snap/kotlin/current'))
    paths = [kotlin / 'bin/kotlinc', kotlin / 'lib/kotlin-compiler.jar',
             kotlin / 'lib/compose-compiler-plugin.jar', kotlin / 'lib/kotlin-stdlib.jar']
    missing = [str(path) for path in paths if not path.exists()]
    if missing:
        raise SystemExit(f'standalone boundary: required toolchain input is absent: {missing[0]}')
    return paths


def runtime_classpath():
    jars = ['build/toolchain/jsengine.jar', 'build/toolchain/guava.jar', 'build/toolchain/failureaccess.jar']
    compose = (ROOT / 'build/compose/classpath.txt').read_text().strip()
    return ':'.join(str(ROOT / jar) for jar in jars) + ':' + compose


def proof_key(paths, android, aidl):
    kotlin = Path(os.environ.get('KOTLIN_HOME', '/snap/kotlin/current'))
    toolchain = [kotlin / 'lib/kotlin-compiler.jar', kotlin / 'lib/compose-compiler-plugin.jar',
                 kotlin / 'lib/kotlin-stdlib.jar', android, aidl,
                 ROOT / 'build/compose/classpath.txt', ROOT / 'tools/compose/dependencies.sha256',
                 ROOT / 'docs/spec-v0.8.md',
                 ROOT / 'build/toolchain/jsengine.jar', ROOT / 'build/toolchain/guava.jar',
                 ROOT / 'build/toolchain/failureaccess.jar']
    missing = [str(path) for path in toolchain if not Path(path).exists()]
    if missing:
        raise SystemExit(f'standalone boundary: required toolchain input is absent: {missing[0]}')
    payload = [str(ROOT / 'tools/boundary-proof.py'), str(ROOT / 'tools/library-inputs.py'),
               str(ROOT / 'tools/library-inputs.txt')]
    return build_cache.fingerprint([str(path) for path in paths] + [str(item) for item in toolchain] + payload)


def stage_tree():
    # Refresh staged source, retaining independently validated compiled outputs. Input changes
    # invalidate the corresponding stage; never copy canonical build outputs into isolation.
    STAGE.mkdir(parents=True, exist_ok=True)
    for name in ('build.sh', 'dependencies.lock.json', 'tools', 'core', 'api', 'ui', 'android', 'docs'):
        source = ROOT / name
        if source.is_dir():
            shutil.rmtree(STAGE / name, ignore_errors=True)
            shutil.copytree(source, STAGE / name)
        else:
            shutil.copy2(source, STAGE / name)
    for name in ('demos', 'tests'):
        # A regular file cannot be traversed: any library read of application source or
        # tests fails the isolated build instead of silently succeeding.
        (STAGE / name).write_text(f'access-failing sentinel: the library build must never read {name}/\n')
    return STAGE


def isolated_digests(android, aidl, prepare_stage=None, plan=False):
    stage = stage_tree()
    output = STAGE / 'output'
    environment = os.environ.copy()
    environment.update({
        'DEAL_ROOT': str(library_inputs.dependency_roots()['deal']),
        'DEAL_UI_ROOT': str(library_inputs.dependency_roots()['deal-ui']),
        'ANDROID_JAR': str(android),
        'AIDL': str(aidl),
        'RUNTIME_CP': runtime_classpath(),
        'OUTPUT_DIR': str(output),
        'KOTLIN_HOME': os.environ.get('KOTLIN_HOME', '/snap/kotlin/current'),
        'DEAL_BUILD_STAGE': prepare_stage or '',
        'DEAL_BUILD_PLAN': '1' if plan else '0',
    })
    log = STAGE / 'invocations.log'
    environment['DEAL_INPUT_LOG'] = str(log)
    tools = STAGE / 'bin'
    tools.mkdir(exist_ok=True)
    real = {name: shutil.which(name) for name in ('javac', 'java', 'python3', 'jar', 'zip', 'aidl')}
    for name, path in real.items():
        if not path:
            continue
        wrapper = tools / name
        wrapper.write_text('#!/usr/bin/env bash\n'
                           'printf "%s\\0" "$(basename "$0")" "$@" >> "$DEAL_INPUT_LOG"\n'
                           f'exec "{path}" "$@"\n')
        wrapper.chmod(0o755)
    environment['JAVA_HOME'] = os.environ.get('JAVA_HOME') or str(Path(real['javac']).resolve().parents[1])
    environment['PATH'] = f'{tools}:{environment["PATH"]}'
    print('[boundary] isolated library build starting', file=sys.stderr, flush=True)
    started = time.monotonic()
    try:
        # A one-stage preparation executes that stage only, so its own declared bound plus the copy and
        # audit is all it may take, and a stage the declaration does not cover is refused by name instead
        # of inheriting a short fallback. A whole proof compiles every stage in sequence, so its outer bound
        # is the sum of the declared bounds: the per-stage bounds in build.sh stay the inner guard that
        # names the stage that stopped instead of an unnamed outer kill. This tree reuses its own validated
        # stages between proofs, so only a changed input makes it cold again: one full build measured 136 s
        # with the Kotlin stage at 57 s, on the same toolchain whose coldest Kotlin measurement (142.6 s)
        # the declaration keeps, because a bound has to contain the worst case rather than the best.
        if prepare_stage:
            bounds = stage_bounds()
            if prepare_stage not in bounds:
                raise SystemExit(f'standalone boundary: no declared preparation bound for stage: {prepare_stage}')
            seconds = bounds[prepare_stage] + 30
            if 'DEAL_BUILD_STAGE_SECONDS' in environment:
                stage_seconds = int(environment['DEAL_BUILD_STAGE_SECONDS'])
                if stage_seconds <= 0:
                    raise SystemExit('standalone boundary: preparation stage bound must be positive')
                seconds = max(seconds, stage_seconds + 5)
        else:
            seconds = isolated_build_seconds()
        subprocess.run(['timeout', '--kill-after=2s', f'{seconds}s', 'bash', 'build.sh'], cwd=stage, env=environment, check=True)
    finally:
        print(f'[boundary] isolated library build elapsed={time.monotonic()-started:.2f}s',
              file=sys.stderr, flush=True)
    if prepare_stage or plan:
        return None
    aar = output / 'deal-embedding.aar'
    if not aar.is_file():
        raise SystemExit(f'standalone boundary: isolated build produced no AAR at {aar}')
    record = read_invocations(log, stage)
    replacements = [(output, b'<output>'), (stage, b'<root>')]
    classes, assets = aar_digests(aar, replacements)
    return {'classes': classes, 'assets': assets, 'invocations': record}, aar


def read_invocations(log, stage):
    """Path arguments the isolated build handed to the wrapped build tools, relative to the stage.
    Absolute toolchain paths passed through environment variables are not recorded here; the
    sentinel build already fails if the library traverses demos/ or tests/."""
    if not log.is_file():
        return []
    paths = set()
    for argument in log.read_bytes().split(b'\0'):
        try:
            text = argument.decode()
        except UnicodeDecodeError:
            continue
        if not text or '=' in text:
            continue
        candidate = Path(text)
        if candidate.is_absolute():
            resolved = candidate.resolve()
            if resolved.is_relative_to(stage):
                paths.add(resolved.relative_to(stage).as_posix())
        elif text.startswith(('demos/', 'tests/')) or text in ('demos', 'tests'):
            paths.add(text)
    return sorted(paths)


def audit_invocations(paths):
    violations = []
    for path in paths:
        if path == 'demos' or path.startswith('demos/'):
            violations.append(f'library build reads application source or tests: {path}')
        elif path == 'tests' or path.startswith('tests/'):
            violations.append(f'library build reads application source or tests: {path}')
    return violations


def demo_declarations(extra_sources=(), extra_jars=()):
    """The production declaration channel: one line per target from `demos/build.sh print-inputs`, the
    same selection function the real compile loop consumes. A control may add an input to the
    declaration, and the gate that stands in front of the compile must refuse it."""
    targets = demo_targets() + ['tests']
    output = subprocess.check_output(['bash', 'demos/build.sh', 'print-inputs', *targets],
                                     cwd=ROOT, text=True)
    declarations = [json.loads(line) for line in output.splitlines() if line.strip()]
    if [item['target'] for item in declarations] != targets:
        raise SystemExit('standalone boundary: demo input declaration is incomplete')
    for declaration in declarations:
        declaration['sources'] = list(declaration['sources']) + list(extra_sources)
        declaration['app_apis'] = list(declaration['app_apis']) + list(extra_jars)
    return declarations


PACKAGED_RUNTIME = {'build/toolchain/jsengine.jar', 'build/toolchain/guava.jar',
                    'build/toolchain/failureaccess.jar'}


def classpath_violations(target, entry, role, kotlin_home=''):
    """Every classpath entry must be the packaged AAR extraction, a pinned runtime jar or the platform
    SDK jar. A framework source, a source tree or a library build tree is a violation."""
    path = Path(entry)
    relative = path.resolve().relative_to(ROOT).as_posix() if path.resolve().is_relative_to(ROOT) else path.as_posix()
    if relative == 'build/embedding-consumer/classes.jar':
        return []
    if relative.startswith('build/embedding-library'):
        return [f'demo compiles a library build tree input instead of the AAR: {relative}']
    if path.suffix in ('.kt', '.java', '.deal', '.dealui') or relative.startswith(
            ('android/src', 'core', 'ui', 'tools', 'demos', 'tests')):
        return [f'demo compiles framework implementation source instead of the AAR: {relative}']
    pinned = relative in PACKAGED_RUNTIME or (relative.startswith('build/compose/') and path.suffix == '.jar')
    stdlib = path.suffix == '.jar' and kotlin_home and path.as_posix() == str(Path(kotlin_home) / 'lib/kotlin-stdlib.jar')
    if pinned or stdlib:
        return []
    return [f'demo compiles a {role} entry outside the packaged AAR and the pinned runtime: {relative}']


def audit_demo(declaration):
    violations = []
    target = declaration['target']
    sources = declaration['sources']
    if not sources:
        violations.append(f'demo/test target {target} declares no source')
    for source in sources:
        relative = Path(source).as_posix()
        if any(character in relative for character in '*?'):
            violations.append(f'demo/test target {target} has an unmatched source pattern: {relative}')
            continue
        application = (relative.startswith('demos/android/apps/') or relative.startswith('tests/android/'))
        generated = relative.startswith(f'build/{target}/')
        if not (application or generated):
            violations.append(f'demo/test target {target} consumes a source outside application code: {relative}')
        if any(relative.startswith(tree) for tree in LIBRARY_SOURCE_TREES):
            violations.append(f'demo compiles framework implementation input instead of the AAR: {relative}')
    if not declaration['embedding']:
        violations.append(f'demo/test target {target} declares no embedding input')
    for embedding in declaration['embedding']:
        relative = Path(embedding).as_posix()
        if relative != 'build/embedding-consumer/classes.jar':
            violations.append(f'demo compiles a non-AAR embedding input: {relative}')
        if relative.startswith('build/embedding-library'):
            violations.append(f'demo compiles a library build tree input instead of the AAR: {relative}')
    # The real compile classpath, not only the embedding jar: app_apis is what kotlinc sees as the
    # embedding types and profile_jars/runtime_cp are the runtime it links against.
    for role in ('app_apis', 'profile_jars', 'runtime_cp'):
        entries = declaration.get(role) or []
        if not entries:
            violations.append(f'demo/test target {target} declares no {role}')
        for entry in entries:
            violations.extend(classpath_violations(target, entry, role, declaration.get('kotlin_home', '')))
    platform = Path(declaration.get('android_jar', '')).as_posix()
    if not re.search(r'/platforms/android-[0-9.]+/android\.jar$', platform):
        violations.append(f'demo compiles against a non-SDK platform jar: {platform}')
    if Path(declaration.get('assets', '')).as_posix() != 'build/embedding-consumer/assets':
        violations.append(f'demo packages assets outside the AAR extraction: {declaration.get("assets")}')
    return violations


def compile_gate(declarations):
    """The gate in front of the demo compile: every audited violation refuses the build."""
    violations = []
    for declaration in declarations:
        violations.extend(audit_demo(declaration))
    return violations


def demo_compile_targets(declarations):
    return [declaration['target'] for declaration in declarations if declaration['target'] != 'tests']


def compile_key(declaration):
    target = declaration['target']
    # Generated target configuration is an output of the compile; its generator is fingerprinted below.
    inputs = [entry for entry in declaration['sources'] if not entry.startswith(f'build/{target}/')]
    paths = [str(ROOT / entry) for entry in inputs + declaration['app_apis'] + declaration['profile_jars']]
    packaging = [declaration['assets'], 'build/compose/resources.txt', 'build/compose/packages.txt',
                 'tools/package-java-resources.py', 'tools/build-demos.sh', 'tools/build-cache.py',
                 declaration['android_jar']]
    if declaration.get('manifest'):
        packaging.append(declaration['manifest'])
    paths += [str(ROOT / entry) for entry in packaging if (ROOT / entry).exists()]
    paths += [str(path) for path in compile_toolchain()]
    android, _aidl, aapt2 = sdk_paths()
    paths += [str(aapt2), str(android)]
    return build_cache.fingerprint(paths)


def missing_compile_inputs(declaration):
    """A declared input that disappears is a violation, never a quietly smaller fingerprint."""
    target = declaration['target']
    declared = [entry for entry in declaration['sources'] if not entry.startswith(f'build/{target}/')]
    declared += declaration['app_apis'] + declaration['profile_jars']
    if declaration.get('manifest'):
        declared.append(declaration['manifest'])
    return [f'demo target {target} declares an absent compile input: {entry}'
            for entry in declared if not (ROOT / entry).exists()]


def packaging_jobs(pending):
    """The demo compile batch runs several independent targets at once. Each target keeps its own build
    tree and the whole batch is still one lock-holding build, so concurrency here shortens the proven
    repackage without changing what is compiled or proving anything in parallel with the tests. The
    default is the same ceiling the production batch declares (`DEMO_JOB_CEILING` in
    `tools/build-demos.sh`): measured cold on this toolchain, the seven declared targets take 547 s over
    two jobs and its own three-job waves are what the canonical batch has always run."""
    requested = os.environ.get('DEAL_DEMO_JOBS', '3')
    if not requested.isdigit() or int(requested) < 1:
        raise SystemExit('standalone boundary: DEAL_DEMO_JOBS must be a positive integer')
    return max(1, min(int(requested), len(pending), os.cpu_count() or 1))


def compile_demos(declarations):
    """Compile and package every demo target from the packaged AAR extraction only.

    This is the only entry point that compiles a demo: it audits every declaration first and refuses
    the build for any violation, so an injected input can never reach a compiler. The production
    target loop (`demos/build.sh`) then compiles, dexes, packages, resource-links and signs each demo.
    An unchanged target is skipped only under an identical validated input fingerprint that covers the
    declared inputs, the packaging inputs, the compiler and the AAR, recorded after its build."""
    violations = compile_gate(declarations)
    if violations:
        return violations, []
    for declaration in declarations:
        violations.extend(missing_compile_inputs(declaration))
    if violations:
        return violations, []
    COMPILE_CACHE.mkdir(parents=True, exist_ok=True)
    pending = []
    for declaration in declarations:
        target = declaration['target']
        if target == 'tests':
            continue
        stamp = COMPILE_CACHE / f'{target}.sha256'
        package = ROOT / f'build/{target}.apk'
        produced = package.is_file()
        expected = compile_key(declaration) + ':' + sha(package.read_bytes()) if produced else ''
        if produced and stamp.is_file() and stamp.read_text().strip() == expected:
            continue
        pending.append(target)
    if pending:
        print(f'[boundary] packaging targets: {", ".join(pending)}', file=sys.stderr, flush=True)
        # The batch size is validated before anything is removed, so a bad DEAL_DEMO_JOBS leaves the
        # previous packages in place instead of deleting them and then aborting.
        environment = os.environ.copy()
        environment['DEAL_BUILD_JOBS'] = str(packaging_jobs(pending))
        # A pending target's previous package is removed first, so the file's existence after the
        # build means this build produced it from the current AAR. A batch that drops, skips or
        # races a target would otherwise leave the stale package in place while the proof recorded
        # the new compile key, and every later run would trust a package it never repackaged.
        for target in pending:
            for produced in (ROOT / f'build/{target}.apk', ROOT / f'build/{target}.apk.idsig'):
                produced.unlink(missing_ok=True)
        started = time.monotonic()
        try:
            subprocess.run(['timeout', '--kill-after=2s', f'{demo_packaging_seconds(pending)}s', 'bash', 'demos/build.sh', *pending], cwd=ROOT, check=True, env=environment)
        finally:
            print(f'[boundary] demo packaging elapsed={time.monotonic()-started:.2f}s',
                  file=sys.stderr, flush=True)
        for declaration in declarations:
            # A key is recorded only for a target whose package this build produced: a dropped or
            # skipped target is refused below instead of leaving a stamp that claims a compile.
            if declaration['target'] in pending and (ROOT / f'build/{declaration["target"]}.apk').is_file():
                (COMPILE_CACHE / f'{declaration["target"]}.sha256').write_text(compile_key(declaration) + ':' + sha((ROOT / f'build/{declaration["target"]}.apk').read_bytes()) + '\n')
    violations = []
    for declaration in declarations:
        target = declaration['target']
        if target == 'tests':
            continue
        if not (ROOT / f'build/{target}.apk').is_file():
            violations.append(f'demo target {target} produced no packaged APK from the AAR')
    return violations, pending


def undeclared_build_script_inputs(paths):
    """Every `$ROOT/...` path build.sh names must be covered by the declared input set."""
    declared = []
    for path in paths:
        resolved = Path(path).resolve()
        if resolved.is_relative_to(ROOT):
            declared.append(resolved.relative_to(ROOT).as_posix().rstrip('/'))
    violations = []
    for token in sorted(set(re.findall(r'\$ROOT/([A-Za-z0-9_./*-]+)', (ROOT / 'build.sh').read_text()))):
        token = token.rstrip('/')
        # These are output/coordination paths, not library source inputs.
        if not token or token in ('build', 'build/.demos-build.lock'):
            continue
        if any(token == entry or token.startswith(entry + '/') or entry.startswith(token + '/')
               for entry in declared):
            continue
        violations.append(f'build.sh reads an input absent from the declared library input set: {token}')
    return violations


def extraction_matches(aar, assets):
    violations = []
    if not EXTRACTION.is_dir():
        return [f'AAR extraction is absent: {EXTRACTION.relative_to(ROOT)}']
    extracted_jar = EXTRACTION / 'classes.jar'
    with zipfile.ZipFile(aar) as archive:
        expected = sha(archive.read('classes.jar'))
    if not extracted_jar.is_file():
        violations.append(f'AAR extraction has no classes.jar: {extracted_jar.relative_to(ROOT)}')
    elif sha(extracted_jar.read_bytes()) != expected:
        violations.append('AAR extraction classes.jar is not byte-identical to the packaged AAR')
    for name, value in compared(assets).items():
        path = EXTRACTION / 'assets' / name
        if not path.is_file():
            violations.append(f'AAR extraction is missing packaged asset: assets/{name}')
        elif sha(path.read_bytes()) != value:
            violations.append(f'AAR extraction asset differs from the packaged AAR: assets/{name}')
    return violations


def negative_controls(declarations):
    """Both directions, observed failing through the same gate the compile consumes.

    The demo controls inject an input into a target's real declaration - the channel
    `demos/build.sh print-inputs` feeds the compile - and the gate in front of the compile must refuse
    it with the offending path. A conforming declaration must still pass the same gate.
    """
    observed = []
    root = ROOT.resolve()
    for path in (root / 'demos/android/apps/calendar/src/PreparationActivity.kt',
                 root / 'tests/tools/test-protocol.js'):
        found = library_inputs.boundary_violations([path])
        if not found:
            raise SystemExit(f'standalone boundary: library negative control did not fail for {path}')
        observed.append(('INPUT_BOUNDARY', found[0]))
    if compile_gate(declarations):
        raise SystemExit(f'standalone boundary: a conforming demo declaration was rejected: {compile_gate(declarations)[0]}')
    controls = [
        ('framework implementation source',
         ['android/src/rendering/DealRenderer.kt'], [], [],
         'demo compiles framework implementation input instead of the AAR: android/src/rendering/DealRenderer.kt'),
        ('library build tree jar',
         [], ['build/embedding-library/classes.jar'], ['build/embedding-library/classes.jar'],
         'demo compiles a library build tree input instead of the AAR: build/embedding-library/classes.jar'),
        ('library build tree runtime jar',
         [], [], ['build/embedding-library/classes.jar'],
         'demo compiles a library build tree input instead of the AAR: build/embedding-library/classes.jar'),
    ]
    for label, extra_sources, extra_jars, extra_runtime, expected in controls:
        injected = demo_declarations(extra_sources, extra_jars)
        if extra_runtime:
            for declaration in injected:
                declaration['profile_jars'] = list(declaration['profile_jars']) + extra_runtime
        # The control enters the compile through the same function the real build uses, so the gate
        # that refuses the build is the one observed failing.
        violations, built = compile_demos(injected)
        if built:
            raise SystemExit(f'standalone boundary: demo {label} control was compiled: {built}')
        if not any(expected == violation for violation in violations):
            raise SystemExit(f'standalone boundary: demo {label} control was not observed failing: {violations[:3]}')
        observed.extend(('DEMO_BOUNDARY', violation) for violation in violations)
    for kind, message in dict.fromkeys(observed):
        print(f'standalone boundary: negative controls observed failing: {kind} {message}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--target', choices=demo_targets(), help='prove one demo; full proof still requires all targets')
    # The choices are the declaration itself, so a newly declared stage cannot be selectable only after
    # someone remembers a second list.
    parser.add_argument('--prepare-stage', choices=sorted(stage_bounds()), help='prepare one bounded isolated-library stage, not a passing boundary proof')
    parser.add_argument('--plan', action='store_true', help='show isolated stage readiness and pending targets without builds')
    args = parser.parse_args()
    (ROOT/'build').mkdir(exist_ok=True)
    lock = (ROOT/'build/.demos-build.lock').open('a')
    if os.environ.get('DEAL_BUILD_LOCK_HELD') != str(ROOT):
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            return 75
    os.environ['DEAL_BUILD_LOCK_HELD'] = str(ROOT)
    # Every outer bound here is derived from `tools/stage-bounds.txt`, so a stage override the declaration
    # does not contain would turn this outer kill into the nameless timeout the derivation prevents. Refuse
    # it by name instead, and point at the one declaration both layers read.
    if os.environ.get('DEAL_BUILD_STAGE_SECONDS', '').strip():
        print(STAGE_OVERRIDE_REFUSAL, file=sys.stderr)
        return 2
    if args.prepare_stage or args.plan:
        android, aidl, _ = sdk_paths()
        # Same isolated tree, tool wrappers and argument audit trail as the final proof.
        isolated_digests(android, aidl, prepare_stage=args.prepare_stage, plan=args.plan)
        print('Boundary preparation only: no proof recorded; each MISS needs its named stage.')
        return 0
    if not AAR.is_file():
        raise SystemExit(f'standalone boundary: the packaged library AAR is absent at '
                         f'{AAR.relative_to(ROOT)}; build the library before this gate item')
    android, aidl, _aapt2 = sdk_paths()
    paths = library_inputs.resolve()
    declared = library_inputs.boundary_violations(paths)
    if declared:
        for violation in declared:
            print(f'standalone boundary: {violation}', file=sys.stderr)
        return 1
    undeclared = undeclared_build_script_inputs(paths)
    if undeclared:
        for violation in undeclared:
            print(f'standalone boundary: {violation}', file=sys.stderr)
        return 1
    canonical_replacements = [(ROOT / 'build/embedding-library', b'<output>'), (ROOT, b'<root>')]
    canonical_classes, canonical_assets = aar_digests(AAR, canonical_replacements)
    raw_classes, raw_assets = aar_digests(AAR)
    key = proof_key(paths, android, aidl)
    record = json.loads(CACHE.read_text()) if CACHE.is_file() else None
    canonical = {'classes': digest_map(canonical_classes), 'assets': digest_map(compared(canonical_assets))}
    excluded = sorted(compared_difference(canonical_assets))
    if excluded:
        print(f'standalone boundary: nondeterministic generated asset digest not claimed: {excluded}')
    declarations = demo_declarations()
    if args.target:
        declarations = [d for d in declarations if d['target'] == args.target]
    # The extraction the compile consumes must first be byte-identical to the packaged AAR, then every
    # demo target compiles and packages against it only. An input outside it, or a declared input that
    # disappeared, refuses the compile.
    violations = extraction_matches(AAR, raw_assets)
    compiled = []
    stale = not (record and record.get('key') == key and record.get('canonical') == canonical)
    if not stale:
        isolated = record['isolated']
    # The isolated library build and the demo repackage are independent preparations: one compiles the
    # library in a tree that holds no canonical output, the other packages every demo from the AAR
    # extraction, and they share no output tree. They are prepared at the same time, each still under its
    # own declared bound, and the proof records nothing until both have finished, so one cold proof is
    # shorter without a bound being relaxed or an assertion skipped.
    with concurrent.futures.ThreadPoolExecutor(max_workers=1) as prepare:
        batch = None if violations else prepare.submit(compile_demos, declarations)
        if not stale:
            print(f'standalone boundary: cached proof for identical validated inputs; '
                  f'classes {isolated["classes"][:16]} assets {isolated["assets"][:16]}')
            print(f'standalone boundary: {len(paths)} declared library input(s); none under demos/ or tests/')
        else:
            if record and record.get('key') == key:
                print('standalone boundary: canonical packaged digests changed; the isolated proof is stale')
            result, aar = isolated_digests(android, aidl)
            invocations = audit_invocations(result['invocations'])
            if invocations:
                for violation in invocations:
                    print(f'standalone boundary: {violation}', file=sys.stderr)
                return 1
            isolated = {'classes': digest_map(result['classes']), 'assets': digest_map(compared(result['assets']))}
            if isolated != canonical:
                changed = [name for name in set(result['classes']) | set(canonical_classes)
                           if result['classes'].get(name) != canonical_classes.get(name)]
                changed += [f'assets/{name}' for name in set(result['assets']) | set(canonical_assets)
                            if result['assets'].get(name) != canonical_assets.get(name)]
                print(f'standalone boundary: isolated build differs from the packaged AAR: {changed[:5]}', file=sys.stderr)
                return 1
            CACHE.parent.mkdir(parents=True, exist_ok=True)
            CACHE.write_text(json.dumps({'key': key, 'canonical': canonical, 'isolated': isolated}, indent=2) + '\n')
            print(f'standalone boundary: isolated library build without demos/ or tests/ matches the packaged '
                  f'AAR content digests; classes {isolated["classes"][:16]} assets {isolated["assets"][:16]}; '
                  f'{len(paths)} declared library input(s) and {len(result["invocations"])} build-tool path '
                  f'argument(s) outside demos/ and tests/')
        if batch is not None:
            compile_violations, compiled = batch.result()
            violations.extend(compile_violations)
    if violations:
        for violation in violations:
            print(f'standalone boundary: {violation}', file=sys.stderr)
        return 1
    print(f'standalone boundary: {len(declarations)} demo/test target(s) declare application sources and '
          f'the AAR extraction only; AAR extraction byte-identical to deal-embedding.aar')
    print(f'standalone boundary: {len(demo_compile_targets(declarations))} demo target(s) compiled and packaged '
          f'from the AAR extraction ({len(compiled)} rebuilt: {", ".join(compiled) or "none"})')
    negative_controls(declarations)
    print('standalone boundary: selected target PASS (not full proof)' if args.target else 'standalone boundary: PASS')
    return 0


def compared_difference(assets):
    return set(assets) - set(compared(assets))


if __name__ == '__main__':
    sys.exit(main())
